#SBATCH --cpus-per-task=8
#SBATCH --mem=16G
#SBATCH --time=02:00:00
#SBATCH --account=class-sbl-30004-ws-2026
#SBATCH --reservation=class-sbl-30004-2026-10-28
#SBATCH --output=/data/users/dpatel/assembly_annotation_course/logs/output/InterProScan_%j.o
#SBATCH --error=/data/users/dpatel/assembly_annotation_course/logs/error/InterProScan_%j.e

# Stop on failed commands, unset variables, or failures within pipelines.
set -euo pipefail

# Course software and project folder
COURSEDIR=/data/courses/genome_annotation_resources/2026
WORKDIR=/data/users/dpatel/assembly_annotation_course

# path to the container
INTERPROSCAN_SIF="$COURSEDIR/containers/InterProScan_5.70.sif"

# Folder with the renamed files (generated by script 21)
FINALDIR="$WORKDIR/output/MAKER_merged/final_gene_annotation"
protein="assembly.all.maker.proteins.fasta" # this contains the merged protein sequences 

# Prevent inherited container settings from changing the course environment.
unset SINGULARITY_BIND APPTAINER_BIND SINGULARITY_TMPDIR

mkdir -p "$FINALDIR/tmp"
cd "$FINALDIR"

# Annotate protein domains with Pfam, plus GO terms and InterPro IDs
# -appl pfam        : use the Pfam database
# --disable-precalc : compute locally, no online lookup
# -f TSV            : tab-separated output
# --goterms         : add Gene Ontology terms
# --iprlookup       : add InterPro entry IDs
# --seqtype p       : input is protein
apptainer exec --cleanenv --pwd "$FINALDIR" \
    --bind "$COURSEDIR/data/interproscan-5.70-102.0/data":/opt/interproscan/data \
    --bind "$COURSEDIR" --bind "$WORKDIR" \
    --bind "$FINALDIR/tmp":/temp \
    "$INTERPROSCAN_SIF" \
    /opt/interproscan/interproscan.sh \
    -appl pfam --disable-precalc -f TSV \
    --goterms --iprlookup --seqtype p \
    -i "${protein}.renamed.fasta" -o output.iprscan